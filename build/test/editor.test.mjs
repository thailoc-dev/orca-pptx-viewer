test('fits the whole slide in a short editor and keeps fitting when it resizes', async () => {
  const { page, frame, errors } = await openEditor(browser, { width: 1200, height: 420 })
  await postFile(page, deck)
  await opened(frame)
  await frame.getByRole('button', { name: 'Fit whole slide' }).click()
  await frame.waitForFunction(() => document.getElementById('percent').textContent !== '100%')
  const fits = () => frame.evaluate(() => {
    const slide = document.querySelector('#slides [data-slide-index] > div')
    return slide.getBoundingClientRect().height <= document.getElementById('viewport').clientHeight
  })
  assert.equal(await fits(), true)
  const before = await frame.locator('#percent').textContent()
  await page.setViewportSize({ width: 1200, height: 600 })
  await frame.waitForFunction((p) => document.getElementById('percent').textContent !== p, before)
  assert.equal(await fits(), true)
  assert.equal(await frame.getByRole('button', { name: 'Fit whole slide' }).getAttribute('aria-pressed'), 'true')
  await frame.getByRole('button', { name: 'Fit to width', exact: true }).click()
  await frame.waitForFunction(() => document.getElementById('percent').textContent === '100%')
  assert.deepEqual(errors, [])
  await page.close()
})

test('reloads a changed file without blanking, and keeps the last good version on a bad save', async () => {
  const { page, frame, errors } = await openEditor(browser)
  await postFile(page, deck)
  await opened(frame)
  await frame.getByRole('button', { name: 'Next slide' }).click()
  await slideIs(frame, 'Slide 2 / 3')
  await frame.evaluate(() => {
    window.__blank = false
    new MutationObserver(() => {
      if (!document.getElementById('message').hidden) window.__blank = true
    }).observe(document.getElementById('message'), { attributes: true })
  })
  await postFile(page, deck)
  await frame.waitForFunction(() => document.getElementById('status').hidden)
  await slideIs(frame, 'Slide 2 / 3')
  assert.equal(await frame.evaluate(() => window.__blank), false)
  await postFile(page, Buffer.from('half-written file'))
  await frame.waitForFunction(() => /could not be read/.test(document.getElementById('status').textContent))
  assert.match(await frame.locator('#slides').innerText(), /Revenue/)
  assert.equal(await frame.locator('#message').isHidden(), true)
  await postFile(page, deck)
  await frame.waitForFunction(() => document.getElementById('status').hidden)
  assert.deepEqual(errors, [])
  await page.close()
})
